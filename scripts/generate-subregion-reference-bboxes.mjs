/**
 * Emit REGION_PACK_SUBREGION_REFERENCE_BBOXES from pack boundary GeoJSON.
 *
 * Usage: node scripts/generate-subregion-reference-bboxes.mjs
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import bbox from "@turf/bbox";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const outPath = join(root, "src/domain/regions/subregionReferenceBboxes.ts");

/** Pack → primary boundary file under public/geo/{pack}/ + feature id property. */
const SOURCES = [
  { packId: "dublin", file: "councils.geojson", idProperty: "councilId" },
  { packId: "london", file: "boroughs.geojson", idProperty: "boroughId" },
  { packId: "nyc", file: "boroughs.geojson", idProperty: "boroughId" },
  { packId: "tokyo", file: "wards.geojson", idProperty: "wardId" },
  { packId: "osaka", file: "wards.geojson", idProperty: "wardId" },
  { packId: "portland-maine", file: "districts.geojson", idProperty: "districtId" },
  { packId: "southampton", file: "wards.geojson", idProperty: "wardId" },
  { packId: "switzerland", file: "cantons.geojson", idProperty: "cantonId" },
  { packId: "australia", file: "states.geojson", idProperty: "stateId" },
  { packId: "zurich", file: "districts.geojson", idProperty: "districtId" },
  { packId: "lucerne", file: "districts.geojson", idProperty: "districtId" },
];

const ROUND_DECIMALS = 4;

function roundCoord(value) {
  const factor = 10 ** ROUND_DECIMALS;
  return Math.round(value * factor) / factor;
}

function featureAabb(feature) {
  const [west, south, east, north] = bbox(feature);
  return {
    south: roundCoord(south),
    west: roundCoord(west),
    north: roundCoord(north),
    east: roundCoord(east),
  };
}

function formatBox(box) {
  return `{ south: ${box.south}, west: ${box.west}, north: ${box.north}, east: ${box.east} }`;
}

function loadPackSubregions(packId, file, idProperty) {
  const path = join(root, "public/geo", packId, file);
  const collection = JSON.parse(readFileSync(path, "utf8"));
  /** @type {Record<string, { south: number; west: number; north: number; east: number }>} */
  const byId = {};
  for (const feature of collection.features ?? []) {
    const id = feature?.properties?.[idProperty];
    if (typeof id !== "string" || !id) {
      continue;
    }
    if (!feature.geometry) {
      continue;
    }
    byId[id] = featureAabb(feature);
  }
  return byId;
}

function emitTs(packs) {
  const packBlocks = Object.entries(packs).map(([packId, byId]) => {
    const entries = Object.entries(byId)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([id, box]) => `    ${JSON.stringify(id)}: ${formatBox(box)},`)
      .join("\n");
    return `  ${JSON.stringify(packId)}: {\n${entries}\n  },`;
  });

  return `import type { BoundingBox } from "@/domain/geometry/gameArea/gameAreaBounds";
import type { RegionPackId } from "./regionPack";

/**
 * Per-subregion reference AABBs from shipped pack boundary GeoJSON.
 * Generated by scripts/generate-subregion-reference-bboxes.mjs. Do not hand-edit.
 */
export const REGION_PACK_SUBREGION_REFERENCE_BBOXES: Partial<
  Record<RegionPackId, Record<string, BoundingBox>>
> = {
${packBlocks.join("\n")}
};
`;
}

/** @type {Record<string, Record<string, { south: number; west: number; north: number; east: number }>>} */
const packs = {};
for (const source of SOURCES) {
  packs[source.packId] = loadPackSubregions(source.packId, source.file, source.idProperty);
}

writeFileSync(outPath, emitTs(packs));
execFileSync(
  process.execPath,
  [join(root, "node_modules/@biomejs/biome/bin/biome"), "format", "--write", outPath],
  { cwd: root, stdio: "inherit" },
);
console.log(`Wrote ${outPath}`);
for (const [packId, byId] of Object.entries(packs)) {
  console.log(`  ${packId}: ${Object.keys(byId).length} subregions`);
}
